#!/usr/bin/env python3
"""The interleave-width table across the #737 machines (#780).

Two steps, both from the repository root:

  python3 benchmarks/interleave_table.py import MACHINE STAMP SESSION_DIR
      Copies a platform session's bench_interleave_rows sweeps
      (interleave-<compiler>-<i>.txt, written by INTERLEAVE=1) to
      benchmarks/data/MACHINE/interleave_rows/STAMP/, and writes one CSV per
      compiler with its .sysinfo sidecar. STAMP is the session's name under
      benchmarks/data/MACHINE/mtl5_bench/, so the sweep and the capability card
      it ran beside stay together; the session must already be published there
      (the same native-t1.json). The sidecar is that session's native-t1 sidecar
      -- the same machine, commit, preflight and clock policy -- with the fields
      that differ for the sweep replaced: label, benchmark, compiler, bench_cpus.

  python3 benchmarks/interleave_table.py table [PAGE]
      Reads every benchmarks/data/*/interleave_rows/*/interleave-*.csv and
      rewrites the generated part of PAGE (default
      docs/benchmarks/interleave-width.md), between its BEGIN and END markers:
      per machine and compiler, the median time per kernel and width over all
      runs of all sessions, and the summaries. The text around the markers is
      hand-written and left alone.

A median over runs, not a count of each run's winner: the first run of a
sweep often favours a narrower width than the runs after it.
"""
import collections
import csv
import glob
import math
import os
import re
import shutil
import statistics
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DATA = os.path.join(ROOT, "benchmarks", "data")
PAGE = os.path.join(ROOT, "docs", "benchmarks", "interleave-width.md")
BEGIN = "<!-- BEGIN generated by benchmarks/interleave_table.py table -->"
END = "<!-- END generated -->"

KERNELS = [("gemv", "gemv"), ("trmv lower", "trmv"), ("lower_trisolve", "trisolve")]
TYPES = ["f64", "f32"]
FIELDS = ["session", "run", "compiler", "compiler_version", "cpu", "vector_registers",
          "n", "reps", "kernel", "type", "width", "is_default", "ms", "gbps"]
HEAD1 = re.compile(r"^# bench_interleave_rows, (.*), cpu (\d+), clock policy: (.*)$")
HEAD3 = re.compile(r"n = (\d+), median of (\d+); vector registers = (\d+)")
ROW = re.compile(r"^(gemv|trmv lower|lower_trisolve)\s+(f32|f64)\s+W=(\d+)\s*(\*?)\s+([\d.]+) ms\s+([\d.]+) GB/s")
SWEEP = re.compile(r"^interleave-(.+)-(\d+)\.txt$")
# Short names for the ISA classes the defaults are proposed for.
ISA = {"x86_64": "x86-64", "AMD64": "x86-64", "aarch64": "AArch64", "arm64": "AArch64"}


def fail(msg):
    sys.exit(f"interleave_table: {msg}")


def read_text(path):
    with open(path, encoding="ascii", errors="strict", newline="") as h:
        return h.read().replace("\r\n", "\n")


def parse_sweep(path):
    """One sweep file -> (header dict, list of row dicts)."""
    lines = read_text(path).split("\n")
    m1, m3 = HEAD1.match(lines[0]), HEAD3.search(lines[2]) if len(lines) > 2 else None
    if not m1 or not m3:
        fail(f"{path}: not a bench_interleave_rows sweep from platform.sh / platform.ps1")
    head = {"compiler_version": m1[1], "cpu": m1[2], "clock_policy": m1[3],
            "n": m3[1], "reps": m3[2], "vector_registers": m3[3]}
    rows = []
    for line in lines[3:]:
        m = ROW.match(line)
        if m:
            rows.append({"kernel": m[1], "type": m[2], "width": m[3], "is_default": int(m[4] == "*"),
                         "ms": m[5], "gbps": m[6]})
    if len(rows) != len(KERNELS) * len(TYPES) * 7:
        fail(f"{path}: {len(rows)} rows, expected {len(KERNELS) * len(TYPES) * 7}")
    return head, rows


def cmd_import(machine, stamp, session):
    card = os.path.join(DATA, machine, "mtl5_bench", stamp)
    if not os.path.isdir(card):
        fail(f"{card} does not exist: publish the session first (benchmarks/publish_platform.cmake)")
    for f in ("native-t1.json", "native-t1.json.sysinfo"):
        if read_text(os.path.join(session, f)) != read_text(os.path.join(card, f)):
            fail(f"{session}/{f} differs from {card}/{f}: not the published session {stamp}")
    sweeps = collections.defaultdict(dict)
    for name in sorted(os.listdir(session)):
        m = SWEEP.match(name)
        if m:
            sweeps[m[1]][int(m[2])] = os.path.join(session, name)
    if not sweeps:
        fail(f"{session}: no interleave-<compiler>-<i>.txt (was the session run with INTERLEAVE=1?)")
    out = os.path.join(DATA, machine, "interleave_rows", stamp)
    if os.path.exists(out):
        fail(f"{out} already exists; the data directory is append-only")
    sidecar = read_text(os.path.join(card, "native-t1.json.sysinfo")).rstrip("\n").split("\n")
    os.makedirs(out)
    for comp, runs in sorted(sweeps.items()):
        heads = {}
        with open(os.path.join(out, f"interleave-{comp}.csv"), "w", encoding="ascii", newline="") as h:
            w = csv.DictWriter(h, fieldnames=FIELDS, lineterminator="\n")
            w.writeheader()
            for i, path in sorted(runs.items()):
                head, rows = parse_sweep(path)
                heads[i] = head
                for r in rows:
                    w.writerow({"session": stamp, "run": i, "compiler": comp, **{k: head[k] for k in
                                ("compiler_version", "cpu", "vector_registers", "n", "reps")}, **r})
                with open(path, encoding="ascii", newline="") as src, \
                        open(os.path.join(out, os.path.basename(path)), "w", encoding="ascii", newline="\n") as dst:
                    dst.write(src.read().replace("\r\n", "\n"))
        if len({(h["compiler_version"], h["cpu"]) for h in heads.values()}) != 1:
            fail(f"{session}: the {comp} runs disagree on the compiler or the CPU")
        first = heads[min(heads)]
        override = {"label": f"interleave-{comp}", "benchmark": "bench_interleave_rows",
                    "compiler": first["compiler_version"], "bench_cpus": first["cpu"]}
        drop = {"class", "compiler_version", "simd_backend", "pool_size", "blas_vendor", "blas_vendor_threads"}
        with open(os.path.join(out, f"interleave-{comp}.csv.sysinfo"), "w", encoding="ascii", newline="\n") as h:
            seen = set()
            for line in sidecar:
                key = line.split("=", 1)[0]
                if key in drop:
                    continue
                if key in override:
                    line = f"{key}={override[key]}"
                seen.add(key)
                h.write(line + "\n")
            for key, value in override.items():
                if key not in seen:
                    h.write(f"{key}={value}\n")
            h.write(f"sidecar_source=mtl5_bench/{stamp}/native-t1.json.sysinfo, the same session\n")
            h.write(f"interleave_runs={len(runs)}\n")
        print(f"interleave_table: {comp}: {len(runs)} runs -> {os.path.relpath(out, ROOT)}")


def load():
    """(machine, compiler) -> {"rows": {(kernel, type, width): [ms]}, "wins": ..., "meta": ...}."""
    found = collections.OrderedDict()
    for path in sorted(glob.glob(os.path.join(DATA, "*", "interleave_rows", "*", "interleave-*.csv"))):
        machine = os.path.relpath(path, DATA).split(os.sep)[0]
        side = dict(l.split("=", 1) for l in read_text(path + ".sysinfo").split("\n") if "=" in l)
        with open(path, encoding="ascii", newline="") as h:
            rows = list(csv.DictReader(h))
        comp = rows[0]["compiler"]
        e = found.setdefault((machine, comp), {"rows": collections.defaultdict(list),
                                               "wins": collections.defaultdict(collections.Counter),
                                               "sessions": set(), "runs": 0, "default": {},
                                               "version": rows[0]["compiler_version"],
                                               "vregs": rows[0]["vector_registers"],
                                               "isa": ISA.get(side.get("cpu_arch", ""), side.get("cpu_arch", "?")),
                                               "cpu": side.get("cpu_brand", "?")})
        per = collections.defaultdict(dict)
        for r in rows:
            key = (r["kernel"], r["type"], int(r["width"]))
            e["rows"][key].append(float(r["ms"]))
            per[(r["session"], r["run"], r["kernel"], r["type"])][int(r["width"])] = float(r["ms"])
            if r["is_default"] == "1":
                e["default"][r["type"]] = int(r["width"])
        for (_, _, k, t), byw in per.items():
            e["wins"][(k, t)][min(byw, key=byw.get)] += 1
        e["sessions"].add(rows[0]["session"])
        e["runs"] += len({(r["session"], r["run"]) for r in rows})
    if not found:
        fail("no benchmarks/data/*/interleave_rows/*/interleave-*.csv; import a session first")
    return found


def cmd_table(page):
    found = load()
    out, summary = [], []
    for (machine, comp), e in found.items():
        widths = sorted({w for (_, _, w) in e["rows"]})
        out += [f"### {machine} -- {comp}", "",
                f"{e['cpu']}; {e['version']}; vector registers {e['vregs']}; built default W = "
                f"{e['default'].get('f64')} (f64), {e['default'].get('f32')} (f32); median of {e['runs']} runs "
                f"({len(e['sessions'])} sessions), each the median of 21. Data: "
                f"`benchmarks/data/{machine}/interleave_rows/`.", "",
                "| kernel | " + " | ".join(f"W={w}" for w in widths) +
                " | fastest | W=6 / fastest | W=6 / W=4 | per-run fastest |",
                "|---|" + "---|" * (len(widths) + 4)]
        for t in TYPES:
            for k, short in KERNELS:
                med = {w: statistics.median(e["rows"][(k, t, w)]) for w in widths}
                best = min(med, key=med.get)
                cells = [f"**{med[w]:.3f}**" if w == best else f"{med[w]:.3f}" for w in widths]
                wins = ", ".join(f"{w}: {c}" for w, c in sorted(e["wins"][(k, t)].items()))
                out.append(f"| {short} {t} | " + " | ".join(cells) +
                           f" | {best} | {med[6] / med[best]:.3f} | {med[6] / med[4]:.3f} | {wins} |")
                summary.append((machine, comp, e["isa"], t, best, med))
        out.append("")
    head = ["### Summary", "",
            "Per machine and compiler: the fastest width of each kernel, and the worst cost of a fixed "
            "width against the fastest (time at that width / time at the fastest; 1.000 is no loss).", "",
            "| machine | ISA | compiler | fastest (f64 gemv, trmv, trisolve / f32 ...) | W=4 | W=6 | W=8 | W=6 / W=4 |",
            "|---|---|---|---|---|---|---|---|"]
    groups = collections.OrderedDict()
    for s in summary:
        groups.setdefault((s[0], s[1], s[2]), []).append(s)
    for (machine, comp, isa), rs in groups.items():
        fast = " / ".join(", ".join(str(r[4]) for r in rs if r[3] == t) for t in TYPES)
        worst = [max(r[5][w] / r[5][r[4]] for r in rs) for w in (4, 6, 8)]
        head.append(f"| {machine} | {isa} | {comp} | {fast} | " + " | ".join(f"{x:.3f}" for x in worst) +
                    f" | {max(r[5][6] / r[5][4] for r in rs):.3f} |")
    head += ["", "### A fixed default per ISA class", "",
             "Time at a fixed width / time at the fastest width, over every machine, compiler, kernel and "
             "type of the class: geometric mean / worst case.", "",
             "| ISA | W=2 | W=4 | W=6 | W=8 | W=12 |", "|---|---|---|---|---|---|"]
    for isa in sorted({s[2] for s in summary}, key=lambda i: (i != "x86-64", i)):
        cells = []
        for w in (2, 4, 6, 8, 12):
            rel = [s[5][w] / s[5][s[4]] for s in summary if s[2] == isa]
            cells.append(f"{math.exp(sum(map(math.log, rel)) / len(rel)):.3f} / {max(rel):.3f}")
        head.append(f"| {isa} | " + " | ".join(cells) + " |")
    head.append("")
    text = read_text(page)
    if BEGIN not in text or END not in text:
        fail(f"{page}: the markers are missing:\n  {BEGIN}\n  {END}")
    before, rest = text.split(BEGIN, 1)
    after = rest.split(END, 1)[1]
    body = "\n".join(head + ["### Per machine", ""] + out)
    with open(page, "w", encoding="ascii", newline="\n") as h:
        h.write(f"{before}{BEGIN}\n\n{body}\n{END}{after}")
    print(f"interleave_table: wrote {os.path.relpath(page, ROOT)} ({len(found)} machine/compiler tables)")


def main(argv):
    if len(argv) == 5 and argv[1] == "import":
        cmd_import(argv[2], argv[3], os.path.abspath(argv[4]))
    elif len(argv) in (2, 3) and argv[1] == "table":
        cmd_table(os.path.abspath(argv[2]) if len(argv) == 3 else PAGE)
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main(sys.argv)
